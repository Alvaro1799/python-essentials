# LITERALS - PE1 Module 2
# Un literal es un valor fijo que se escribe directamente en el código

# Inteegers
print(10)
print(-5)

# Floats
print(3.14)
print(-0.5)

# Strings
print("Hola, mundo!")
print('tambien con comillas simples')
print("""Multilinea
con comillas triples""")

# Booleans
print(True)
print(False)

# Escape sequences
print("Hola\nMundo")  # \n Nueva línea
print("Hola\tMundo")  # \t Tabulación
